export function fileExtension(path: string) {
  const name = path.trim().split(/[\\/]/).pop() || "";
  const dotIndex = name.lastIndexOf(".");
  return dotIndex > 0 ? name.slice(dotIndex + 1).toLowerCase() : "";
}

export function isTextPreviewPath(path: string) {
  return textPreviewExtensions.has(fileExtension(path));
}

export function isFileViewerPreviewPath(path: string) {
  const extension = fileExtension(path);
  return textPreviewExtensions.has(extension) || fileViewerPreviewExtensions.has(extension);
}

export function isFileViewerSearchPath(path: string) {
  const extension = fileExtension(path);
  return textPreviewExtensions.has(extension) || fileViewerSearchExtensions.has(extension);
}

export function isPreviewablePath(path: string) {
  return isTextPreviewPath(path) || isFileViewerPreviewPath(path);
}

export function previewModeForPath(_path: string): FilePreviewMode {
  return "viewer";
}

export function shouldConfirmLargeFileViewerPreview(mode: FilePreviewMode, sizeBytes: number | null | undefined) {
  return mode === "viewer" && typeof sizeBytes === "number" && sizeBytes > FILE_VIEWER_LARGE_FILE_CONFIRM_BYTES;
}

export function filePreviewToolbarPosition(_path: string): FilePreviewToolbarPosition {
  return "top";
}

export function isPdfPreviewPath(path: string) {
  return fileExtension(path) === "pdf";
}

export function isImagePreviewPath(path: string) {
  return ["png", "jpg", "jpeg", "webp", "gif", "bmp", "svg", "tiff", "tif", "avif", "ico", "heic", "heif", "jxl"].includes(fileExtension(path));
}

export function isVideoPreviewPath(path: string) {
  return ["mp4", "m4v", "webm", "mov", "ogv", "ogg", "mkv", "avi", "3gp", "3gpp", "m3u8"].includes(fileExtension(path));
}
